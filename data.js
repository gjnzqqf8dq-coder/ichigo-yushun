/* 各計測時点の順位。品質スコアの降順で決まる。 */
function rankAt(leg, no) {
  var v = LINES.map(function (l) { return { no: l.no, s: l.race[leg] }; })
    .sort(function (a, b) { return b.s - a.s; });
  for (var i = 0; i < v.length; i++) if (v[i].no === no) return i + 1;
  return 6;
}
function rankSeq(no) { return RACE.legs.map(function (x, i) { return rankAt(i, no); }); }

